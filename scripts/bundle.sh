#!/bin/zsh
# Builds a release binary and wraps it in dist/Iris.app (ad-hoc signed).
set -euo pipefail
cd "${0:a:h}/.."

swift build -c release
BIN="$(swift build -c release --show-bin-path)/FileDropUtility"
APP="dist/Iris.app"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS"
cp "$BIN" "$APP/Contents/MacOS/FileDropUtility"

cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleExecutable</key><string>FileDropUtility</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundleIdentifier</key><string>local.filedroputility</string>
  <key>CFBundleName</key><string>Iris</string>
  <key>CFBundleDisplayName</key><string>Iris</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>0.1.0</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSMinimumSystemVersion</key><string>26.0</string>
  <key>LSUIElement</key><true/>
  <key>LSApplicationCategoryType</key><string>public.app-category.utilities</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSSpeechRecognitionUsageDescription</key><string>Transcribe turns speech in your audio and video into subtitles, on this Mac.</string>
</dict>
</plist>
PLIST
# Finder Quick Actions / Services. Each item sends runQuickAction (ServiceProvider.swift)
# with a QuickAction spec as NSUserData; DropCore's QuickActionTests checks these specs.
service() {  # service <menu title> <QuickAction spec> <file type UTI>...
  local title=$1 spec=$2 types="" uti; shift 2
  for uti in "$@"; do types+="<string>$uti</string>"; done
  print -r -- "<dict>
    <key>NSMenuItem</key><dict><key>default</key><string>$title</string></dict>
    <key>NSMessage</key><string>runQuickAction</string>
    <key>NSPortName</key><string>Iris</string>
    <key>NSUserData</key><string>$spec</string>
    <key>NSRequiredContext</key><dict/>
    <key>NSSendFileTypes</key><array>$types</array>
  </dict>"
}
DOCUMENTS=(public.plain-text public.rtf public.html net.daringfireball.markdown
  org.openxmlformats.wordprocessingml.document com.microsoft.word.doc org.oasis-open.opendocument.text
  com.apple.iwork.pages.sffpages com.apple.iwork.pages.pages org.idpf.epub-container
  org.openxmlformats.spreadsheetml.sheet org.openxmlformats.presentationml.presentation
  com.microsoft.excel.xls com.microsoft.powerpoint.ppt com.apple.iwork.keynote.sffkey com.apple.keynote.key
  com.apple.iwork.numbers.sffnumbers com.apple.numbers.numbers org.oasis-open.opendocument.spreadsheet
  public.comma-separated-values-text public.tab-separated-values-text)
SERVICES=$(
  service "Convert Image to PNG" convert-image:png public.image
  service "Convert Image to JPEG" convert-image:jpeg public.image
  service "Convert Video to MP4" convert-video:mp4 public.movie
  service "Convert to MP3" convert-audio:mp3 public.audio public.movie
  service "Convert Document to PDF" convert-document:pdf $DOCUMENTS
  service "Compress Images, PDFs and Videos" compress public.image com.adobe.pdf public.movie
  service "Resize Image to 50%" resize:50% public.image
  service "Make PDF from Files" make-pdf public.image com.adobe.pdf
)
plutil -replace NSServices -xml "<array>$SERVICES</array>" "$APP/Contents/Info.plist"

# Optional: UPDATE_FEED_URL=https://api.github.com/repos/<owner>/<repo>/releases/latest
# turns on the "Check for updates daily" setting. Without it the app never checks.
if [[ -n "${UPDATE_FEED_URL:-}" ]]; then
  [[ "$UPDATE_FEED_URL" == https://* ]] || { echo "UPDATE_FEED_URL must be https" >&2; exit 1; }
  /usr/libexec/PlistBuddy -c "Add :FDUUpdateFeedURL string $UPDATE_FEED_URL" "$APP/Contents/Info.plist"
fi

# The wheel's highlight sound (generated by DropCore's HighlightSound; see Resources/).
mkdir -p "$APP/Contents/Resources"
cp Resources/Highlight.wav "$APP/Contents/Resources/Highlight.wav"
# The app icon (sources and how to rebuild it: Resources/AppIcon/README.md).
cp Resources/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"

# Bundled helpers (see scripts/fetch-tools.sh): Mach-O tools in Contents/Helpers, the
# ExifTool Perl distribution and all licences in Contents/Resources.
TOOLS="Vendor/out"
if [[ -x "$TOOLS/bin/ffmpeg" && -x "$TOOLS/bin/cwebp" && -f "$TOOLS/exiftool/exiftool" ]]; then
  mkdir -p "$APP/Contents/Helpers" "$APP/Contents/Resources"
  cp "$TOOLS/bin/ffmpeg" "$TOOLS/bin/ffprobe" "$TOOLS/bin/cwebp" "$APP/Contents/Helpers/"
  [[ -x "$TOOLS/bin/mac" ]] && cp "$TOOLS/bin/mac" "$APP/Contents/Helpers/"
  cp -R "$TOOLS/exiftool" "$APP/Contents/Resources/exiftool"
  cp -R "$TOOLS/licenses" "$APP/Contents/Resources/Licenses"
  for tool in "$APP"/Contents/Helpers/*; do codesign --force --sign - "$tool"; done
else
  echo "warning: bundled tools missing; run scripts/fetch-tools.sh (media, WebP and metadata tools will be unavailable)" >&2
fi

codesign --force --sign - "$APP"
echo "Built $APP"
